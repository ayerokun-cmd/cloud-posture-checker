"""Generate docs/sample-report.md against a SIMULATED AWS account (moto). No real AWS is touched.

Usage: python scripts/make_sample_report.py
"""

import json
import os
from pathlib import Path

for key in ("AWS_PROFILE", "AWS_DEFAULT_PROFILE"):
    os.environ.pop(key, None)
os.environ.update(
    AWS_ACCESS_KEY_ID="testing",
    AWS_SECRET_ACCESS_KEY="testing",
    AWS_DEFAULT_REGION="us-east-1",
)

import boto3  # noqa: E402
from moto import mock_aws  # noqa: E402

from posture_checker.context import Context  # noqa: E402
from posture_checker.registry import run_checks  # noqa: E402
from posture_checker.report import Report  # noqa: E402

REGIONS = ["us-east-1", "eu-west-1"]
ADMIN = {"Version": "2012-10-17", "Statement": [{"Effect": "Allow", "Action": "*", "Resource": "*"}]}


def seed(session: boto3.Session) -> None:
    """A typical small account: some good controls, some common gaps."""
    iam = session.client("iam")
    iam.update_account_password_policy(MinimumPasswordLength=8, PasswordReusePrevention=24)
    iam.create_user(UserName="jane.admin")
    iam.create_login_profile(UserName="jane.admin", Password="Example-Passw0rd!")
    iam.create_user(UserName="deploy-bot")
    iam.create_access_key(UserName="deploy-bot")
    iam.create_access_key(UserName="deploy-bot")
    policy = iam.create_policy(PolicyName="LegacyFullAccess", PolicyDocument=json.dumps(ADMIN))
    iam.attach_user_policy(UserName="deploy-bot", PolicyArn=policy["Policy"]["Arn"])

    s3 = session.client("s3")
    for name in ("acme-public-assets", "acme-cloudtrail-logs"):
        s3.create_bucket(Bucket=name)
    s3.put_public_access_block(
        Bucket="acme-cloudtrail-logs",
        PublicAccessBlockConfiguration={k: True for k in (
            "BlockPublicAcls", "IgnorePublicAcls", "BlockPublicPolicy", "RestrictPublicBuckets")},
    )

    ct = session.client("cloudtrail")
    ct.create_trail(Name="management-events", S3BucketName="acme-cloudtrail-logs",
                    IsMultiRegionTrail=True, EnableLogFileValidation=True)
    ct.start_logging(Name="management-events")

    for region in REGIONS:
        ec2 = session.client("ec2", region_name=region)
        vpc = ec2.describe_vpcs()["Vpcs"][0]["VpcId"]
        sg = ec2.create_security_group(GroupName="legacy-bastion", Description="ssh", VpcId=vpc)
        ec2.authorize_security_group_ingress(GroupId=sg["GroupId"], IpPermissions=[
            {"IpProtocol": "tcp", "FromPort": 22, "ToPort": 22, "IpRanges": [{"CidrIp": "0.0.0.0/0"}]}])
    session.client("ec2", region_name="us-east-1").enable_ebs_encryption_by_default()

    kms = session.client("kms", region_name="us-east-1")
    rotated = kms.create_key(Description="app-data")["KeyMetadata"]["KeyId"]
    kms.enable_key_rotation(KeyId=rotated)
    kms.create_key(Description="legacy-backups")


def main() -> None:
    with mock_aws():
        session = boto3.Session(region_name="us-east-1")
        seed(session)
        ctx = Context(session, REGIONS)
        report = Report.build(run_checks(ctx), ctx.account_id, REGIONS)
    out = Path(__file__).resolve().parents[1] / "docs" / "sample-report.md"
    out.parent.mkdir(exist_ok=True)
    note = (
        "> **Sample output.** Generated by `scripts/make_sample_report.py` against a simulated "
        "AWS account ([moto](https://github.com/getmoto/moto)) seeded with common misconfigurations. "
        "No real account was scanned.\n\n"
    )
    out.write_text(note + report.to_markdown(), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
